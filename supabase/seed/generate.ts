/**
 * Generates supabase/seed.sql from data.ts + domain defaults.
 *   npm run seed:generate
 * The Supabase CLI runs seed.sql on `supabase db reset`. IDs are deterministic (UUID from a name),
 * so the same seed always produces the same rows.
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { makeCalendar } from "../../domain/calendar";
import { schedule } from "../../domain/schedule";
import { DEFAULT_COST, DEFAULT_DEPARTMENTS, DEFAULT_SETTINGS, DEFAULT_STATION_TYPES, SETTINGS_SCHEMAS } from "../../domain/settings";
import type { Task } from "../../domain/types";
import { auditEntries, crew, projects, templates, workstations } from "./data";

const TZ = DEFAULT_SETTINGS.calendar.timezone;
// D9: the v1 plans were made on 08:00–17:00; the seed re-plans them on the current default calendar
// (same days, order and durations). data.ts keeps the literal v1 plans for the engine-parity tests.
const CAL = makeCalendar(DEFAULT_SETTINGS);

export function uuidFor(...parts: string[]): string {
  const h = createHash("sha1").update("kynetik:" + parts.join("/")).digest("hex");
  // RFC 4122 v5 layout
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h.slice(16, 18), 16) & 0x3f) | 0x80).toString(16)}${h.slice(18, 20)}-${h.slice(20, 32)}`;
}

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const ts = (local: string | null | undefined) => (local ? `(${q(local)}::timestamp at time zone ${q(TZ)})` : "null");
const num = (n: number | null | undefined) => (n == null ? "null" : String(n));
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const out: string[] = [];
const sql = (s: string) => out.push(s);
const insert = (table: string, rows: Record<string, string>[]) => {
  if (!rows.length) return;
  const cols = Object.keys(rows[0]);
  sql(`insert into public.${table} (${cols.join(", ")}) values\n  ${rows.map((r) => `(${cols.map((c) => r[c]).join(", ")})`).join(",\n  ")};`);
};

sql("-- GENERATED by supabase/seed/generate.ts from supabase/seed/data.ts — do not edit by hand.");
sql("-- v1 live data snapshot (spec §17, 2026-10-01).");
sql("begin;");
sql("set local app.skip_audit = 'on';");

// ───────────── settings ─────────────
for (const key of Object.keys(SETTINGS_SCHEMAS) as (keyof typeof SETTINGS_SCHEMAS)[]) {
  SETTINGS_SCHEMAS[key].parse(DEFAULT_SETTINGS[key]); // fail fast if defaults drift from schema
}
insert("settings", (Object.keys(SETTINGS_SCHEMAS) as (keyof typeof SETTINGS_SCHEMAS)[]).map((key) => ({
  key: q(key), value: json(DEFAULT_SETTINGS[key]),
})));
insert("settings_cost", [{
  currency: q(DEFAULT_COST.currency),
  default_loading_pct: num(DEFAULT_COST.defaultLoadingPct),
  working_days_per_month: num(DEFAULT_COST.workingDaysPerMonth),
}]);

insert("station_types", [...DEFAULT_STATION_TYPES, { key: "other", label: "Other", colour: DEFAULT_SETTINGS.labels.otherColour }]
  .map((s, i) => ({ key: q(s.key), label: q(s.label), colour: q(s.colour), sort: num(i) })));

insert("departments", DEFAULT_DEPARTMENTS.map((d, i) => ({
  id: q(uuidFor("dept", d.key)), key: q(d.key), name: q(d.name), colour: q(d.colour), emoji: q(d.emoji), sort: num(i),
})));

// ───────────── shop ─────────────
const wsId = (legacy: string) => uuidFor("ws", legacy);
insert("workstations", workstations.map((w, i) => ({
  id: q(wsId(w.id)), legacy_id: q(w.id), name: q(w.name), station_type: q(w.type), sort: num(i),
})));

const personId = (legacy: string) => uuidFor("person", legacy);
const personByName = new Map(crew.map((c) => [c.name, personId(c.id)]));
insert("people", crew.map((c) => ({
  id: q(personId(c.id)), legacy_id: q(c.id), name: q(c.name), crew: q(""), cost_class: q("production"),
})));
insert("people_cost", crew.map((c) => ({
  person_id: q(personId(c.id)), base_salary: num(c.baseSalary), loading_pct: num(c.loadingPct),
})));

// ───────────── templates ─────────────
const tplId = (key: string) => uuidFor("template", key);
// The v1 templates stay for the v1 builds but are archived: new projects use Exterior panels (migration 20261012000200).
insert("templates", templates.map((t) => ({ id: q(tplId(t.key)), key: q(t.key), label: q(t.label), archived: "true" })));
for (const t of templates) {
  insert("template_stages", t.stages.map((s, i) => ({
    id: q(uuidFor("tstage", t.key, s.name)), template_id: q(tplId(t.key)), name: q(s.name),
    station_type: q(s.stationType), part_hours: num(s.partHours), sort: num(i),
  })));
  let n = 0;
  insert("template_tasks", t.stages.flatMap((s) => s.tasks.map((task) => ({
    id: q(uuidFor("ttask", t.key, s.name, task.name)), template_id: q(tplId(t.key)),
    template_stage_id: q(uuidFor("tstage", t.key, s.name)), name: q(task.name), dur_h: num(task.durH), sort: num(n++),
  }))));
  insert("template_parts", t.parts.map((p, i) => ({
    id: q(uuidFor("tpart", t.key, p)), template_id: q(tplId(t.key)), name: q(p), sort: num(i),
  })));
}

// Amends 2026-10-12 (AM-01): the 10-stage Exterior panels workflow for new projects. Live databases get it from
// migration 20261012000200 (same names and station types); a fresh one gets it here, after its station types.
const PANEL_STAGES: [string, string, string][] = [
  ["Modelling", "modelling", "modelling"], ["3D printing", "modification", "printing"], ["Prototyping", "modification", "prototyping"],
  ["Pre-mold production", "modification", "premold"], ["Mold production", "modification", "mold"],
  ["Carbon fibre component production", "modification", "carbon"], ["Fitment", "fitment", "fitment"],
  ["Paint preparation & painting", "paint", "paint"], ["Sanding & polishing", "paint", "sanding"], ["Assembly", "fitment", "assembly"],
];
insert("templates", [{ id: q(tplId("exteriorPanels")), key: q("exteriorPanels"), label: q("Exterior panels"), archived: "false" }]);
insert("template_stages", PANEL_STAGES.map(([name, type, step], i) => ({
  id: q(uuidFor("tstage", "exteriorPanels", name)), template_id: q(tplId("exteriorPanels")), name: q(name),
  station_type: q(type), part_hours: num(0), sort: num(i), step: q(step),
})));

// ───────────── builds ─────────────
const pId = (legacy: string) => uuidFor("project", legacy);
for (const p of projects) {
  const t = templates.find((x) => x.key === p.template);
  if (!t) throw new Error(`Template ${p.template} missing for ${p.serial}`);
  if (p.stations.length !== t.stages.length) throw new Error(`${p.serial}: stations/stages mismatch`);
  const allTasks = t.stages.flatMap((s) => s.tasks.map((task) => ({ stage: s.name, ...task })));
  if (p.tasks.length !== allTasks.length) throw new Error(`${p.serial}: ${p.tasks.length} task plans for ${allTasks.length} tasks`);

  const drafts: Task[] = allTasks.map((task, i) => ({
    id: String(i), num: i + 1, stageId: task.stage, name: task.name, assignee: null, status: "todo", durH: task.durH, pct: 0,
    start: null, end: null, pinnedStart: null, actualStart: null, actualEnd: null, notes: "",
  }));
  const plan = schedule({ startDate: p.startDate, tasks: drafts }, CAL);

  insert("projects", [{
    id: q(pId(p.id)), legacy_id: q(p.id), serial: q(p.serial), name: q(p.name), template_id: q(tplId(t.key)),
    template_label: q(t.label), client: q(p.client), notes: q(p.notes), start_date: q(p.startDate),
    delivery_date: q(p.deliveryDate), status: q(p.status), plan_end: ts(plan.planEnd),
    created_at: p.createdAt ? `${q(p.createdAt)}::timestamptz` : "now()",
  }]);

  const stageId = (name: string) => uuidFor("stage", p.id, name);
  insert("stages", t.stages.map((s, i) => ({
    id: q(stageId(s.name)), project_id: q(pId(p.id)), name: q(s.name), station_type: q(s.stationType),
    station_id: p.stations[i] ? q(wsId(p.stations[i]!)) : "null", part_hours: num(s.partHours), sort: num(i),
  })));

  const parts = p.hasParts ? t.parts : [];
  const partId = (name: string) => uuidFor("part", p.id, name);
  insert("parts", parts.map((name, i) => ({ id: q(partId(name)), project_id: q(pId(p.id)), name: q(name), sort: num(i) })));

  insert("tasks", allTasks.map((task, i) => {
    const v1 = p.tasks[i];
    const planned = plan.tasks[i];
    return {
      id: q(uuidFor("task", p.id, String(i + 1))), project_id: q(pId(p.id)), stage_id: q(stageId(task.stage)),
      num: num(i + 1), name: q(task.name), status: q(v1.status ?? "todo"), dur_h: num(task.durH),
      pct: num(v1.pct ?? (v1.status === "done" ? 100 : 0)), plan_start: ts(planned.start), plan_end: ts(planned.end),
      actual_start: ts(v1.actualStart), actual_end: ts(v1.actualEnd),
    };
  }));
  // Baseline = plan for every v1 build.
  insert("baselines", allTasks.map((_, i) => ({
    task_id: q(uuidFor("task", p.id, String(i + 1))), project_id: q(pId(p.id)),
    start_at: ts(plan.tasks[i].start), end_at: ts(plan.tasks[i].end),
  })));

  // One work item per stage × part; the v1 entries override the defaults.
  insert("work_items", t.stages.flatMap((s) => parts.map((part) => {
    const w = p.work.find((x) => x.stage === s.name && x.part === part);
    const tech = w ? personByName.get(w.tech) : undefined;
    if (w && !tech) throw new Error(`Unknown technician ${w.tech}`);
    return {
      id: q(uuidFor("work", p.id, s.name, part)), project_id: q(pId(p.id)), stage_id: q(stageId(s.name)),
      part_id: q(partId(part)), status: q(w?.status ?? "todo"), tech_id: q(tech ?? null),
      start_at: ts(w?.start), end_at: ts(w?.end), seg_start: ts(w?.start),
    };
  })));
  for (const w of p.work) {
    if (!t.stages.some((s) => s.name === w.stage) || !parts.includes(w.part)) {
      throw new Error(`${p.serial}: work item ${w.stage}/${w.part} has no matching stage/part`);
    }
  }
}

// ───────────── audit (§17.6) ─────────────
insert("audit_log", auditEntries.map((a) => ({
  at: `${q(a.at)}::timestamptz`, actor_role: q(a.role), action: q(a.action), entity: q("projects"),
  entity_id: q(pId(a.project)), project_id: q(pId(a.project)), label: q(a.label),
})));

sql("commit;");

const target = join(__dirname, "..", "seed.sql");
writeFileSync(target, out.join("\n\n") + "\n");
console.log(`Wrote ${target} (${out.length} statements)`);
